"""Audit of the committed continual run's gate (results/mas_continual/gates.jsonl, days.jsonl), by window,
and the served mixture's measured budget compliance; plus the new-action probability table.

  python -m pace.experiments.mas_continual.gate_audit audit --run results/mas_continual \\
      --out results/mas_continual/gate_audit.md
  python -m pace.experiments.mas_continual.gate_audit newmass --run results/mas_continual/gate_v2/default_seed0_rerun \\
      --committed results/mas_continual --out results/mas_continual/new_action_mass.md

Reads only; writes the two markdown files named on the command line.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

from . import analyze

ARMS = ("continual", "continual_awr")
WINDOWS = ((1, 40), (6, 40))


def _crit(t: dict) -> str:
    return " + ".join(c for c, k in (("over budget", "over_budget"), ("quality regressed", "regressed")) if t[k]) or "–"


def _est(rows: list[dict]) -> dict:
    tq = np.array([g["truth"]["candidate"]["quality"] for g in rows])
    tc = np.array([g["truth"]["candidate"]["cost"] - g["prefix_cost"] for g in rows])
    tt = np.array([g["truth"]["candidate"]["cost"] for g in rows])
    q = np.array([g["dr_quality"] for g in rows]); c = np.array([g["dr_cost"] for g in rows])
    pre = np.array([g["prefix_cost"] for g in rows])
    return {"q_bias": float(np.mean(q[:, 0] - tq)), "q_rmse": float(np.sqrt(np.mean((q[:, 0] - tq) ** 2))),
            "q_width": float(np.mean(q[:, 2] - q[:, 1])), "q_cov": float(np.mean((q[:, 1] <= tq) & (tq <= q[:, 2]))),
            "c_bias": float(np.mean(c[:, 0] - tc)), "c_rmse": float(np.sqrt(np.mean((c[:, 0] - tc) ** 2))),
            "c_width": float(np.mean(c[:, 2] - c[:, 1])), "c_cov": float(np.mean((c[:, 1] <= tc) & (tc <= c[:, 2]))),
            # the v1 cost interval shifted by the log's mean prefix, scored against the TOTAL held-out cost
            "t_cov": float(np.mean((c[:, 1] + pre <= tt) & (tt <= c[:, 2] + pre))),
            "ess": float(np.mean([g["per_decision_ess"] / g["per_decision_n"] for g in rows])),
            "n_mean": float(np.mean([g["n"] for g in rows]))}


def audit(run: Path) -> str:
    data = analyze.load(run)
    cfg = data["meta"]["config"]
    B, tol = cfg["budget"], cfg["tol"]
    gates, days = data["gates"], data["days"]
    L = ["# Gate audit of the committed continual run (default schedule, seed 0)", "",
         f"Source: `{run}/gates.jsonl` and `days.jsonl` (committed; read only). B = {B}, tol = {tol}, ε_q = {cfg['eps_q']}. "
         "`acceptable` is the run's own simulator label: candidate held-out quality ≥ incumbent held-out quality − ε_q AND "
         "candidate held-out total cost ≤ B + tol (150 held-out tasks per stage). Generated by "
         "`python -m pace.experiments.mas_continual.gate_audit audit`.", "",
         "## 1. Gate decisions by window", "",
         "| arm | window | gates | PROMOTE | REVERT | promotions of unacceptable candidates (day: criterion) | REVERT of acceptable (false alarms) | REVERT of unacceptable | correct |",
         "|---|---|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        for lo, hi in WINDOWS:
            rows = [g for g in gates if g["arm"] == arm and lo <= g["day"] <= hi]
            P = [g for g in rows if g["decision"] == "PROMOTE"]; R = [g for g in rows if g["decision"] == "REVERT"]
            bad_p = [g for g in P if not g["truth"]["acceptable"]]
            fa = [g for g in R if g["truth"]["acceptable"]]; rr = [g for g in R if not g["truth"]["acceptable"]]
            corr = sum(g["gate_correct"] for g in rows)
            bp = "; ".join(f"d{g['day']}: {_crit(g['truth'])}" for g in bad_p) or "none"
            rr_s = "; ".join(f"d{g['day']}: {_crit(g['truth'])}" for g in rr) or "–"
            L.append(f"| {arm} | {lo}–{hi} | {len(rows)} | {len(P)} | {len(R)} | {len(bad_p)} ({bp}) | {len(fa)} | {len(rr)} "
                     f"({rr_s}) | "
                     f"{corr}/{len(rows)} ({100 * corr / max(len(rows), 1):.0f}%) |")
    L += ["", "## 2. Estimator statistics by window (gate's DR against the candidate's held-out value on the current stage)", "",
          "| arm | window | n gates | mean episodes / gate | mean per-decision ESS / n | DR quality bias / RMSE / mean 90% CI width / coverage | "
          "DR decision cost (net of prefix) bias / RMSE / mean CI width / coverage | same cost interval + mean prefix, coverage of held-out TOTAL cost |",
          "|---|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        for lo, hi in WINDOWS:
            rows = [g for g in gates if g["arm"] == arm and lo <= g["day"] <= hi]
            e = _est(rows)
            L.append(f"| {arm} | {lo}–{hi} | {len(rows)} | {e['n_mean']:.0f} | {e['ess']:.2f} | {e['q_bias']:+.3f} / {e['q_rmse']:.3f} / {e['q_width']:.3f} / {100 * e['q_cov']:.0f}% | "
                     f"{e['c_bias']:+.4f} / {e['c_rmse']:.4f} / ${e['c_width']:.4f} / {100 * e['c_cov']:.0f}% | {100 * e['t_cov']:.0f}% |")
    # which window the paper's gate-history table used
    allw = {arm: [g for g in gates if g["arm"] == arm] for arm in ARMS}
    L += ["", "## 3. Which window the paper's gate-history table used", "",
          "The paper's gate-history table (`\\label{tab:gatehist}`, caption \"Gate history and estimator accuracy against simulator truth ..., "
          "days after warm-up (35 gates, mean n = 370 episodes per gate)\"; Table 12 in the current `main.aux` build; presumably the reviewer's Table 13) "
          "is copied from RESULTS.md §6 / §6a, which `analyze.py` generates with two different windows:", "",
          "| table row | generated by | window actually used |", "|---|---|---|",
          "| candidates PROMOTE / REVERT (8 / 32; 14 / 26) | `analyze.table_gates` | **days 1–40** (all 40 gates; no day filter) |",
          "| REVERT right / false alarm (9 / 23; 0 / 26) | `analyze.table_gates` | **days 1–40** |",
          "| PROMOTE right / missed (8 / 0; 14 / 0) | `analyze.table_gates` | **days 1–40** |",
          "| mean per-decision ESS / n (0.54; 0.25) | `analyze.table_gates` | **days 1–40** |",
          "| mean DR quality / cost CI width (0.200 / $0.0079; 0.653 / $0.0144) | `analyze.table_gates` | **days 1–40** |",
          "| DR quality bias / RMSE / coverage | `analyze.table_estimator_accuracy`, row \"after warm-up\" | days 6–40 |",
          "| DR cost bias / RMSE / coverage | `analyze.table_estimator_accuracy`, row \"after warm-up\" | days 6–40 |",
          "| per-decision SNIPS bias / RMSE | `analyze.table_estimator_accuracy`, row \"after warm-up\" | days 6–40 |", "",
          "So the caption's \"days after warm-up (35 gates, mean n = 370)\" is true only of the three estimator-accuracy rows; the decision "
          f"counts, ESS and CI widths are over all 40 gates (mean n = {np.mean([g['n'] for g in allw['continual']]):.0f}). "
          "Sections 1 and 2 above give every quantity for both windows. Note also that the cost rows of that table are the DECISION cost "
          "net of the prefix (the v1 gate's quantity), scored against held-out total cost minus the log's mean prefix.", ""]

    # served mixture's budget compliance
    gen_rng = analyze.stage_ranges(data["meta"], max(r["day"] for r in days))
    first_prom = {arm: analyze.first_promotion(gates, arm) for arm in ARMS}
    L += ["## 4. The served policy's measured budget compliance, per stage", "",
          "The policy in service is the incumbent's iterate mix, served STATEWISE (`Controller.probs` averages the snapshots' action "
          "probabilities per state) with ε = 0.1 exploration; tests/test_mixture_semantics.py shows that statewise averaging need not "
          "preserve a budget each snapshot meets. What the deployed mixture actually spent: realised mean total cost per task on the served "
          f"traffic (96 tasks/day, prefix included) and its held-out Monte Carlo expected cost (150 tasks) on the day's stage, against B + tol = {B + tol:.3f}. "
          f"Until the first promotion (continual day {first_prom['continual']}, continual_awr day {first_prom['continual_awr']}) the "
          "served policy is the uniform initial policy, not a trained mixture; the `after first promotion` columns restrict to days served by a promoted mixture.", "",
          "| arm | stage | days | served cost, mean (min–max over days) | days served > B + tol | held-out cost of the serving policy, mean (max) | held-out days > B + tol | "
          "after first promotion: days / served mean / days > B + tol / held-out mean / held-out days > B + tol |",
          "|---|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        rows = sorted([r for r in days if r["arm"] == arm], key=lambda r: r["day"])
        for gi, a, b in gen_rng + [(None, 1, 40)]:
            rs = [r for r in rows if a <= r["day"] <= b]
            sc = np.array([r["served"]["cost"] for r in rs])
            hc = np.array([r["heldout"][str(r["gen_index"])]["cost"] for r in rs])
            fp = first_prom[arm] or 99
            post = [(r["served"]["cost"], r["heldout"][str(r["gen_index"])]["cost"]) for r in rs if r["day"] > fp]
            ps = (f"{len(post)} / ${np.mean([p[0] for p in post]):.4f} / {sum(p[0] > B + tol for p in post)} / "
                  f"${np.mean([p[1] for p in post]):.4f} / {sum(p[1] > B + tol for p in post)}") if post else "0 / – / – / – / –"
            label = f"g{gi}" if gi is not None else "all"
            L.append(f"| {arm} | {label} ({a}–{b}) | {len(rs)} | ${sc.mean():.4f} (${sc.min():.4f}–${sc.max():.4f}) | {int((sc > B + tol).sum())} | "
                     f"${hc.mean():.4f} (${hc.max():.4f}) | {int((hc > B + tol).sum())} | {ps} |")
    L += ["", "Served cost is realised on that day's 96 tasks (sampling noise ≈ ±$0.002 per day); the held-out cost is the expected cost "
          "of the same served policy (ε included) on the stage's fixed held-out tasks.", ""]
    return "\n".join(L)


def newmass(run: Path, committed: Path | None) -> str:
    days = [json.loads(l) for l in (run / "days.jsonl").read_text().splitlines() if l.strip()]
    meta = json.loads((run / "meta.jsonl").read_text().splitlines()[0])
    eps = meta["config"]["eps"]
    repro = ""
    if committed is not None and (committed / "days.jsonl").exists():
        old = [json.loads(l) for l in (committed / "days.jsonl").read_text().splitlines() if l.strip()]
        key = lambda r: (r["day"], r["arm"])
        om = {key(r): r for r in old}
        same = sum(1 for r in days if key(r) in om and all(r["served"].get(k) == v for k, v in om[key(r)]["served"].items())
                   and r["heldout"] == om[key(r)]["heldout"])
        ga = [json.loads(l) for l in (committed / "gates.jsonl").read_text().splitlines() if l.strip()]
        gb = [json.loads(l) for l in (run / "gates.jsonl").read_text().splitlines() if l.strip()]
        sg = sum(all(y.get(k) == v for k, v in x.items() if k not in ("train_s", "gate_s")) for x, y in zip(ga, gb))
        repro = (f"The re-run reproduces the committed run exactly: {same} of {len(old)} `days.jsonl` rows (every committed served and "
                 f"held-out field, compared for equality) and {sg} of {len(ga)} `gates.jsonl` rows (every field but wall-clock timings). "
                 "The re-run's served records additionally carry fields added to the code after the committed run "
                 "(`delegate_share`, verifier/retry counters) and the `new_action_mass` field.")
    gens = {g["index"]: g for g in meta["generations"]}
    L = ["# Probability the served policy put on newly introduced actions", "",
         f"Default schedule, seed 0, re-run of the committed configuration into `{run}` with `--log-new-action-mass 1` "
         "(logging only; nothing the run decides depends on it). " + repro, "",
         "For each stage that adds actions, on every logged decision of the stage's days at which at least one newly introduced action was legal: "
         "the served policy's probability (ε = 0.1 included) summed over the new legal actions, against the ε-exploration floor "
         "ε·|new ∩ legal| / |legal| (what the new actions get from exploration alone); and the mean probability of the single most likely new "
         "action against ε/|legal|. `no-ε` is the policy's own softmax mass. The policy serving a stage's first day is the incumbent "
         "promoted under the previous stage (with zero-logit rows for the new actions).", "",
         "| arm | stage (event day) | new actions | stage day | decisions with a new action legal / all | mass on new actions | ε floor | mass / floor | no-ε mass | "
         "max single new action | ε/\\|legal\\| | share of decisions that chose a new action |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        for r in sorted([r for r in days if r["arm"] == arm and "new_action_mass" in r], key=lambda r: r["day"]):
            m = r["new_action_mass"]
            if m["stage_day"] not in (1, 2, 3, 8) or not m.get("n_states"):
                continue
            g = gens[r["gen_index"]]
            L.append(f"| {arm} | {g['name']} (day {g['day']}) | {', '.join(m['new_actions'])} | {m['stage_day']} | {m['n_states']} / {m['n_decisions']} | "
                     f"{m['mass']:.3f} | {m['floor']:.3f} | {m['mass'] / m['floor']:.2f}× | {m['mass_no_eps']:.3f} | {m['per_action_max']:.3f} | "
                     f"{m['per_action_floor']:.3f} | {m['chosen_share']:.3f} |")
    L += ["", "Rows are the 1st, 2nd, 3rd and 8th (last) day of each stage that introduces actions (g1 is a repricing and adds none).", ""]
    # per-action detail on the first day
    L += ["Per new action, mean served probability on the stage's first day (over decisions where it was legal):", ""]
    for arm in ARMS:
        for r in sorted([r for r in days if r["arm"] == arm and "new_action_mass" in r and r["new_action_mass"]["stage_day"] == 1], key=lambda r: r["day"]):
            m = r["new_action_mass"]
            if m.get("n_states"):
                L.append(f"- {arm}, {r['generation']}: " + ", ".join(f"{a} {p:.3f}" for a, p in m["by_action"].items()))
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    a1 = sub.add_parser("audit"); a1.add_argument("--run", default="results/mas_continual"); a1.add_argument("--out", required=True)
    a1.add_argument("--append", default=None, help="markdown file appended verbatim (authored notes)")
    a2 = sub.add_parser("newmass"); a2.add_argument("--run", required=True); a2.add_argument("--committed", default=None)
    a2.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    if a.cmd == "audit":
        text = audit(Path(a.run))
        if a.append and Path(a.append).exists():
            text += "\n" + Path(a.append).read_text()
    else:
        text = newmass(Path(a.run), Path(a.committed) if a.committed else None)
    out = Path(a.out)
    if out.exists() and out.resolve().parent == Path("results/mas_continual").resolve() and out.name not in ("gate_audit.md", "new_action_mass.md"):
        raise SystemExit(f"refusing to overwrite {out}")
    out.write_text(text)
    print(f"[gate_audit] wrote {out}")


if __name__ == "__main__":
    main()
