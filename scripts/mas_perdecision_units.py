"""Per-decision MAS estimates under both units (decision-weighted vs task-weighted).

Re-runs the per-decision SNIPS / DR of `pace.experiments.mas.run.controller_hook` on the uniform
exploration episodes of results/mas/mas_b2b.jsonl, for the committed policy
results/mas/policy_awr_orm.json and the committed ORM results/mas/quality_model.json, with
unit="decision" (the numbers in results/mas/RESULTS.md section 5) and unit="task". Writes
results/mas/perdecision_units.md (RESULTS.md is not touched).

  python scripts/mas_perdecision_units.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pace.controller import Controller  # noqa: E402
from pace.experiments.mas.offpolicy import STEP_CLIP, episode_level, per_decision  # noqa: E402
from pace.experiments.mas.orm import QualityModel, relabel_episodes  # noqa: E402
from pace.trace import read_jsonl  # noqa: E402


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--log", default="results/mas/mas_b2b.jsonl")
    ap.add_argument("--policy", default="results/mas/policy_awr_orm.json")
    ap.add_argument("--qm", default="results/mas/quality_model.json")
    ap.add_argument("--out", default="results/mas/perdecision_units.md")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--boot", type=int, default=200)
    a = ap.parse_args(argv)
    eps_ = read_jsonl(a.log)
    explore = [e for e in eps_ if (e.meta or {}).get("mode", "").startswith("controller")
               and any(s.propensity < 1.0 for s in e.steps)]
    qm = QualityModel.load(a.qm)
    rel = relabel_episodes(explore, qm)
    pol = Controller.load(a.policy)
    lens = np.array([len(e.steps) for e in explore])
    est = {}
    for unit in ("decision", "task"):
        est[unit] = {"hat": per_decision(rel, pol, "quality", a.boot, a.seed, unit=unit),
                     "out": per_decision(explore, pol, "quality", a.boot, a.seed, unit=unit),
                     "cost": per_decision(explore, pol, "cost_to_go", a.boot, a.seed, unit=unit)}
    el_hat = episode_level(rel, pol, "quality", STEP_CLIP, a.boot, a.seed)
    el_out = episode_level(explore, pol, "quality", STEP_CLIP, a.boot, a.seed)
    el_cost = episode_level(explore, pol, "cost", STEP_CLIP, a.boot, a.seed)
    f = lambda t: f"{t[0]:.3f} [{t[1]:.3f}, {t[2]:.3f}]"
    fc = lambda t: f"{t[0]:.4f} [{t[1]:.4f}, {t[2]:.4f}]"
    step_cost = np.mean([sum(s.cost for s in e.steps) for e in explore])
    total = np.mean([e.total_cost for e in explore])
    L = ["# MAS per-decision estimates: decision unit vs task unit", "",
         f"Generated by `scripts/mas_perdecision_units.py` from `{a.log}`: the {len(explore)} uniform-exploration "
         f"episodes ({lens.sum()} logged decisions; decisions per episode min {lens.min()}, median "
         f"{int(np.median(lens))}, max {lens.max()}), policy `{a.policy}`, ORM `{a.qm}`, {a.boot} episode-bootstrap "
         f"resamples (seed {a.seed}), 90% CIs. `results/mas/RESULTS.md` is unchanged; its section 5 rows are the "
         "decision-unit rows below.", "",
         "Estimands (see `pace/experiments/mas/offpolicy.py`):", "",
         "- **decision unit**: every logged decision row has weight 1. Quality is the decision-weighted mean of the "
         "one-decision-intervention value, so an episode with n decisions counts n times. Cost is the mean over "
         "rows of the cost-to-go from the intervened decision; cost-to-go values of one episode overlap, so this is "
         "not a cost per task.",
         "- **task unit**: each episode's rows are weighted 1/n_decisions, so every task counts once. Quality is the "
         "task-average of the one-decision-intervention value. Cost is the total episode cost per task, "
         "prefix + cost-to-go, where the prefix includes the policy-independent planner + first-worker cost "
         f"(${total - step_cost:.4f}/task here, which is not in any logged step) and the logged steps before the "
         "decision.", "",
         "| unit | estimator | n | ESS | quality_hat [90% CI] | outcome quality [90% CI] | cost [90% CI] |",
         "|---|---|---|---|---|---|---|"]
    for unit, lbl in (("decision", "cost-to-go"), ("task", "total/task")):
        e = est[unit]
        L.append(f"| {unit} | uniform behavior, on-policy mean | {e['out']['n']} | {e['out']['n']} | "
                 f"{e['hat']['behavior']:.3f} | {e['out']['behavior']:.3f} | {lbl} {e['cost']['behavior']:.4f} |")
        for k, name in (("snips", "AWR (ORM), per-decision SNIPS"), ("dr", "AWR (ORM), per-decision DR")):
            L.append(f"| {unit} | {name} | {e['out']['n']} | {e['out']['ess']:.1f} | {f(e['hat'][k])} | "
                     f"{f(e['out'][k])} | {lbl} {fc(e['cost'][k])} |")
    L.append(f"| episode | uniform behavior, on-policy mean | {el_out['n']} | {el_out['n']} | {el_hat['behavior']:.3f} | "
             f"{el_out['behavior']:.3f} | total/task {el_cost['behavior']:.4f} |")
    L.append(f"| episode | AWR (ORM), episode SN-IPS, step clip {STEP_CLIP:g} | {el_out['n']} | {el_out['ess']:.1f} | "
             f"{f(el_hat['snips'])} | {f(el_out['snips'])} | total/task {fc(el_cost['snips'])} |")
    d, t = est["decision"], est["task"]
    L += ["", "Side by side (point estimates, AWR policy):", "",
          "| quantity | decision unit | task unit |", "|---|---|---|"]
    for k, name in (("snips", "SNIPS"), ("dr", "DR")):
        L.append(f"| quality_hat, {name} | {d['hat'][k][0]:.3f} | {t['hat'][k][0]:.3f} |")
        L.append(f"| outcome quality, {name} | {d['out'][k][0]:.3f} | {t['out'][k][0]:.3f} |")
        L.append(f"| cost, {name} | {d['cost'][k][0]:.4f} (cost-to-go per decision) | {t['cost'][k][0]:.4f} (total per task) |")
    L.append(f"| behaviour outcome quality | {d['out']['behavior']:.3f} | {t['out']['behavior']:.3f} |")
    L.append(f"| behaviour cost | {d['cost']['behavior']:.4f} (cost-to-go per decision) | {t['cost']['behavior']:.4f} (total per task) |")
    L += ["", "ESS: decision unit is Kish over decision rows (out of n decisions); task unit is Kish over tasks of "
          "the per-task weight Σ_t w_t / n_decisions (out of n tasks). Under the task unit the behaviour row equals "
          "the episode-level on-policy mean, as it should: both are means over tasks."]
    dq = lambda u, k: est[u]["out"][k][0] - est[u]["out"]["behavior"]
    L += ["", "## Reading", "",
          f"The unit changes the sign of the outcome-quality lift that DR reports for the AWR policy: "
          f"{dq('decision', 'dr'):+.3f} against the behaviour under the decision unit, {dq('task', 'dr'):+.3f} under "
          f"the task unit (SNIPS: {dq('decision', 'snips'):+.3f} vs {dq('task', 'snips'):+.3f}). Both lifts sit well "
          "inside 90% CIs that are about 0.3 to 0.5 wide on 30 tasks, so neither unit supports a quality claim on "
          "this log. The two units differ because exploration episodes have 1 to "
          f"{lens.max()} decisions, and the decision unit up-weights the long ones. The decision-unit cost "
          "(mean cost-to-go per decision row) is not on the scale of the budget. The task-unit cost is total "
          f"cost per task: DR {est['task']['cost']['dr'][0]:.4f} against the behaviour's {est['task']['cost']['behavior']:.4f}, "
          "which can be compared with a per-task budget directly. Both units still value one changed decision with "
          "the rest of the trajectory as logged; neither is the full-policy value (the episode-level row)."]
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
